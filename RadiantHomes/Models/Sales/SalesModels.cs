    public static class ConversationStatuses
    {
        public const string Open = "Open";
        public const string Closed = "Closed";
    }

    /// <summary>A customer's chat with a company, about a home or a project, routed to an agent.</summary>
    public class Conversation
    {
        public Guid Id { get; set; }
        public Guid CompanyId { get; set; }
        public HousingCompany Company { get; set; } = null!;
        public Guid? ProjectId { get; set; }
        public HouseProject? Project { get; set; }
        public Guid? ApartmentHouseId { get; set; }
        public ApartmentHouse? ApartmentHouse { get; set; }
        public Guid CustomerId { get; set; }
        public Customer Customer { get; set; } = null!;
        [MaxLength(450)]
        public string CustomerUserId { get; set; } = string.Empty;
        [MaxLength(450)]
        public string? AgentUserId { get; set; }
        [MaxLength(200)]
        public string Subject { get; set; } = string.Empty;
        [MaxLength(20)]
        public string Status { get; set; } = ConversationStatuses.Open;
        public DateTime CreatedOn { get; set; }
        public DateTime LastMessageOn { get; set; }
        public Guid? LeadId { get; set; }
        public List<ChatMessage> Messages { get; set; } = new();
    }

    public class ChatMessage
    {
        public long Id { get; set; }
        public Guid ConversationId { get; set; }
        public Conversation Conversation { get; set; } = null!;
        [MaxLength(450)]
        public string SenderUserId { get; set; } = string.Empty;
        [MaxLength(150)]
        public string SenderName { get; set; } = string.Empty;
        public bool FromCustomer { get; set; }
        [MaxLength(2000)]
        public string Body { get; set; } = string.Empty;
        public DateTime SentOn { get; set; }
        /// <summary>The other side read it.</summary>
        public DateTime? ReadOn { get; set; }
        /// <summary>Generated by the sender's browser; the same id twice (double click, retry) is stored once.</summary>
        public Guid ClientMessageId { get; set; }
    }

    public static class SiteVisitStatuses
    {
        public const string Requested = "Requested";
        public const string RescheduleRequested = "RescheduleRequested";
        public const string Confirmed = "Confirmed";
        public const string Rejected = "Rejected";
        public const string Cancelled = "Cancelled";
        public const string Completed = "Completed";
        public const string NoShow = "NoShow";

        public static readonly string[] Open = { Requested, RescheduleRequested, Confirmed };

        public static string Label(string? s) => s switch
        {
            Requested => "Requested",
            RescheduleRequested => "New time requested",
            Confirmed => "Confirmed",
            Rejected => "Declined",
            Cancelled => "Cancelled",
            Completed => "Visited",
            NoShow => "Didn't come",
            _ => s ?? string.Empty,
        };

        public static string Badge(string? s) => s switch
        {
            Confirmed => "text-bg-success",
            Requested or RescheduleRequested => "text-bg-warning",
            Completed => "text-bg-info",
            Rejected or NoShow => "text-bg-danger",
            _ => "text-bg-secondary",
        };
    }


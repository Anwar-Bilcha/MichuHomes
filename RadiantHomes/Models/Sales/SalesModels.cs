    /// <summary>One video call request and what happened to it.</summary>
    public class CallLog
    {
        public Guid Id { get; set; }
        [MaxLength(80)]
        public string Room { get; set; } = string.Empty;
        public Guid? CompanyId { get; set; }
        public Guid? ProjectId { get; set; }
        public Guid? ApartmentHouseId { get; set; }
        [MaxLength(450)]
        public string CustomerUserId { get; set; } = string.Empty;
        [MaxLength(150)]
        public string CustomerName { get; set; } = string.Empty;
        [MaxLength(40)]
        public string? CustomerPhone { get; set; }
        [MaxLength(300)]
        public string? Topic { get; set; }
        [MaxLength(20)]
        public string Status { get; set; } = CallStatuses.Waiting;
        public DateTime RequestedOn { get; set; }
        public DateTime? AnsweredOn { get; set; }
        public DateTime? EndedOn { get; set; }
        [MaxLength(450)]
        public string? AgentUserId { get; set; }
        [MaxLength(256)]
        public string? AgentName { get; set; }
        [MaxLength(500)]
        public string? Reason { get; set; }

        public int? DurationSeconds => AnsweredOn is DateTime a && EndedOn is DateTime e ? (int)(e - a).TotalSeconds : null;
    }

